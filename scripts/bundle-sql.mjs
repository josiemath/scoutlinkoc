// Combines every migration into supabase/setup.sql, so a new Supabase project
// can be set up by pasting one file into the SQL editor.
//
//   npm run db:bundle
//
// src/tests/sql-bundle.test.ts fails if setup.sql is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function bundleMigrations() {
  const dir = join(root, "supabase", "migrations");
  const files = readdirSync(dir).filter((name) => name.endsWith(".sql")).sort();
  const header = [
    "-- ScoutLink OC database setup: every migration in order.",
    "-- Generated by `npm run db:bundle` from supabase/migrations. Don't edit by hand.",
    "--",
    "-- Paste into the Supabase SQL editor of a NEW project and run once.",
    "-- For an existing project, run only the migrations it hasn't had yet.",
    ""
  ].join("\n");
  const parts = files.map((name) => `-- ===========================================================================\n-- ${name}\n-- ===========================================================================\n\n${readFileSync(join(dir, name), "utf8").trim()}\n`);
  return `${header}\n${parts.join("\n")}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, "supabase", "setup.sql"), bundleMigrations());
  console.log("Wrote supabase/setup.sql");
}
